-- V17：补 I9 缺失的唯一索引（M2 收尾自查发现）。
--
-- FSM §4.5.4 / I9 写的是"一块电池同一时刻至多一条生效绑定"，V8 建表时
-- 只落了 `active_user`（一人至多一块，服务于 M2 的一人一电池口径），
-- `active_battery` 生成列**建了但没建唯一索引** —— 于是 DDL 与不变式不一致：
--   同一个 battery_id 可以同时有两条 ACTIVE 绑定（分给两个用户），
--   而代码里的绑定写入不会报错，只在事后对账时才看得出来。
-- 这类"生成列写了、索引忘了"的错误很典型：列的存在让人误以为约束已经生效。
--
-- 只加索引，不改列：active_battery 的定义本来就是 CASE WHEN ACTIVE THEN battery_id。
-- ============================================================

CREATE UNIQUE INDEX uk_bind_active_battery ON swap_battery_binding (active_battery);
